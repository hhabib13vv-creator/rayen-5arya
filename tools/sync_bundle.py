#!/usr/bin/env python3
"""Sync custom-content.json -> photos/ + custom-content.js (no dependencies).

Run this from the project folder after you export a new bundle from Meme Lab
and save it as custom-content.json:

    python3 tools/sync_bundle.py

What it does:
  * photos embedded as base64 are written byte-for-byte (no re-encoding, no
    resizing, no compression) into photos/
  * custom-content.json is rewritten to reference those files ("file": "photos/..")
    and your original export is first copied into original/
  * custom-content.js is regenerated; it is what lets index.html work when
    opened directly from disk (file://), where fetch() of a .json is blocked.
"""
import base64, json, os, re, shutil, sys, time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JSON_PATH = os.path.join(ROOT, 'custom-content.json')
JS_PATH = os.path.join(ROOT, 'custom-content.js')
PHOTOS = os.path.join(ROOT, 'photos')
EXT = {'image/png': '.png', 'image/jpeg': '.jpg', 'image/webp': '.webp', 'image/gif': '.gif'}
SAFE = re.compile(r'^photos/[\w][\w .()-]*\.(png|jpe?g|webp|gif)$', re.I)


def safe_name(name, mime, used):
    base = re.sub(r'[^\w .()-]', '_', os.path.basename(name or 'photo')).strip(' .') or 'photo'
    stem, ext = os.path.splitext(base)
    if ext.lower() not in ('.png', '.jpg', '.jpeg', '.webp', '.gif'):
        stem, ext = base, EXT.get(mime, '.png')
    cand, i = stem + ext, 2
    while cand.lower() in used:
        cand = f'{stem}_{i}{ext}'; i += 1
    used.add(cand.lower())
    return cand


def main():
    with open(JSON_PATH, encoding='utf-8') as f:
        data = json.load(f)
    if data.get('format') != 'FRIEND.EXE-CUSTOM' or not isinstance(data.get('photos'), list):
        sys.exit('custom-content.json is not a FRIEND.EXE-CUSTOM bundle')
    os.makedirs(PHOTOS, exist_ok=True)
    has_b64 = any(isinstance(p.get('data'), str) for p in data['photos'])
    if has_b64:
        os.makedirs(os.path.join(ROOT, 'original'), exist_ok=True)
        backup = os.path.join(ROOT, 'original', time.strftime('custom-content.%Y%m%d-%H%M%S.json'))
        shutil.copyfile(JSON_PATH, backup)
        print('backed up your export ->', os.path.relpath(backup, ROOT))
    used = set()
    out = []
    for i, p in enumerate(data['photos']):
        item = {'name': p.get('name', f'photo-{i+1}'), 'caption': p.get('caption', '')}
        if isinstance(p.get('data'), str):
            m = re.match(r'data:(image/[\w+.-]+);base64,(.*)$', p['data'], re.S)
            if not m or m.group(1) not in EXT:
                sys.exit(f'photo {i+1}: unsupported or non-base64 image data')
            raw = base64.b64decode(m.group(2))
            fname = safe_name(item['name'], m.group(1), used)
            target = os.path.join(PHOTOS, fname)
            if os.path.exists(target) and open(target, 'rb').read() != raw:
                fname = safe_name('x_' + fname, m.group(1), used)   # never overwrite a different file
                target = os.path.join(PHOTOS, fname)
            with open(target, 'wb') as f:
                f.write(raw)
            item['file'] = 'photos/' + fname
        elif isinstance(p.get('file'), str) and SAFE.match(p['file']):
            if not os.path.isfile(os.path.join(ROOT, p['file'])):
                print('WARNING: missing file', p['file'])
            item['file'] = p['file']
        else:
            sys.exit(f'photo {i+1}: needs "data" (data:image/...) or "file" (photos/...)')
        out.append(item)
    bundle = {'format': 'FRIEND.EXE-CUSTOM', 'version': 1, 'photos': out,
              'letter': data.get('letter', ''), 'reveal': data.get('reveal', ''),
              'revealIndex': data.get('revealIndex', 0)}
    text = json.dumps(bundle, indent=2, ensure_ascii=False)
    with open(JSON_PATH, 'w', encoding='utf-8') as f:
        f.write(text + '\n')
    with open(JS_PATH, 'w', encoding='utf-8') as f:
        f.write('/* Generated by tools/sync_bundle.py from custom-content.json. Do not edit by hand.\n'
                '   A plain <script> works on file:// where fetch() of a .json file is blocked. */\n'
                'window.FRIEND_EXE_BUNDLE = ' + text + ';\n')
    print(f'{len(out)} photos referenced; wrote custom-content.json and custom-content.js')


if __name__ == '__main__':
    main()
